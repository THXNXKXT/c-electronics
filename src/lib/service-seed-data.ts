const text = (value: string): ArticleNode => ({ type: "text", text: value });
const paragraph = (value: string): ArticleNode => ({
  type: "paragraph",
  content: [text(value)],
});
const heading = (value: string, level: 2 | 3 = 2): ArticleNode => ({
  type: "heading",
  attrs: { level },
  content: [text(value)],
});
const bulletList = (items: string[]): ArticleNode => ({
  type: "bulletList",
  content: items.map((item) => ({
    type: "listItem",
    content: [paragraph(item)],
  })),
});

function buildServiceDocument(blueprint: ServiceDraftBlueprint): ArticleDocument {
  return {
    type: "doc",
    content: [
      heading(blueprint.title),
      paragraph(blueprint.overview),
      paragraph(
        "รายละเอียดนี้จัดทำเป็นข้อมูลตั้งต้นสำหรับตรวจทานกับทางร้านก่อนเผยแพร่ ขอบเขตงาน ราคา ระยะเวลา พื้นที่ให้บริการ อะไหล่ และเงื่อนไขหลังบริการขึ้นกับหน้างานจริง จึงควรส่งข้อมูลอุปกรณ์และนัดสำรวจก่อนตัดสินใจ",
      ),
      ...blueprint.sections.flatMap((section) => [
        heading(section.heading),
        ...section.paragraphs.map(paragraph),
      ]),
      heading("ขอบเขตความปลอดภัยที่ต้องยึดถือ"),
      paragraph(
        "ผู้ใช้งานตรวจสภาพภายนอกและรวบรวมข้อมูลได้เมื่อทำอย่างปลอดภัย แต่ไม่ควรถอด ดัดแปลง หรือทดลองในจุดเสี่ยง งานที่เกี่ยวข้องกับไฟฟ้า ความสูง ความร้อน หรือพลังงานสะสมควรให้ช่างที่มีเครื่องมือเหมาะสมดำเนินการ",
      ),
      bulletList(blueprint.safety),
      heading("ข้อมูลที่ช่วยให้ประเมินงานได้ตรงขึ้น"),
      paragraph(
        "ควรเตรียมภาพรวมหน้างาน ภาพป้ายรุ่น อาการที่พบ เวลาที่เริ่มเกิดอาการ สิ่งที่เปลี่ยนไปก่อนหน้า และข้อจำกัดของพื้นที่ ภาพต้องถ่ายจากตำแหน่งที่ปลอดภัย ไม่เข้าใกล้สายไฟ จุดร้อน หรือขอบอาคารเพื่อให้ได้ข้อมูลเพิ่ม",
      ),
      paragraph(
        "เมื่อได้รับข้อมูลแล้ว ทางร้านจะช่วยแนะนำขั้นตอนถัดไปและนัดตรวจหน้างานตามความเหมาะสม ก่อนเริ่มงานควรยืนยันรายการที่จะทำ ค่าใช้จ่ายโดยประมาณ ระยะเวลา อะไหล่ และเงื่อนไขรับประกันกับทางร้านอีกครั้ง",
      ),
      heading("นัดหมายและขอคำแนะนำ"),
      paragraph(
        `หากต้องการประเมิน${blueprint.title.replace(/^บริการ/, "งาน")} กรุณาส่งรายละเอียดที่เตรียมไว้ผ่านช่องทางติดต่อหรือแบบฟอร์มจองบริการ ทีมงานจะใช้ข้อมูลนั้นประกอบการคุยเบื้องต้นและยืนยันนัดหมาย โดยไม่สรุปสาเหตุหรือราคาจากภาพเพียงอย่างเดียว`,
      ),
    ],
  };
}

