async function main() {
  const [serviceRows, productRows] = await Promise.all([
    db.select().from(services).where(eq(services.archived, false)),
    db.select().from(products).where(eq(products.archived, false)),
  ]);

  let created = 0;
  let skipped = 0;

  for (const seed of seedArticles) {
    const [existing] = await db
      .select({ id: articles.id })
      .from(articles)
      .where(eq(articles.slug, seed.slug))
      .limit(1);
    if (existing) {
      skipped += 1;
      continue;
    }

    const service = serviceRows.find((row) => {
      const haystack = `${row.name} ${row.slug}`.toLocaleLowerCase("th");
      return seed.serviceKeywords.some((keyword) =>
        haystack.includes(keyword.toLocaleLowerCase("th")),
      );
    });
    const relatedProducts = productRows
      .filter((row) => {
        const haystack =
          `${row.name} ${row.category} ${row.slug}`.toLocaleLowerCase("th");
        return seed.productKeywords.some((keyword) =>
          haystack.includes(keyword.toLocaleLowerCase("th")),
        );
      })
      .slice(0, 3);
    const id = crypto.randomUUID();

    await db.insert(articles).values({
      id,
      title: seed.title,
      slug: seed.slug,
      excerpt: seed.excerpt,
      content: buildDocument(seed),
      category: seed.category,
      tags: seed.tags,
      coverImage: service?.image ?? null,
      coverImageAlt: service?.image
        ? `ภาพบริการ${seed.category}จาก C.Electronics`
        : null,
      relatedServiceId: service?.id ?? null,
      status: "draft",
      featured: false,
      noIndex: false,
    });

    if (relatedProducts.length) {
      await db.insert(articleProducts).values(
        relatedProducts.map((product) => ({
          articleId: id,
          productId: product.id,
        })),
      );
    }
    created += 1;
  }

  console.log(
    `Article drafts ready: ${created} created, ${skipped} already existed.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
