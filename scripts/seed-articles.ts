import { db } from "@/db";
import {
  articleProducts,
  articles,
  products,
  services,
} from "@/db/schema";
import type { ArticleDocument, ArticleNode } from "@/lib/articles";
import { eq } from "drizzle-orm";

type Section = {
  heading: string;
  paragraphs: string[];
  subheading?: string;
  bullets?: string[];
};

type SeedArticle = {
  title: string;
  slug: string;
  excerpt: string;
  category: string;
  tags: string[];
  serviceKeywords: string[];
  productKeywords: string[];
  intro: string[];
  safetyStop: string[];
  checklist: string[];
  sections: Section[];
  closing: string;
};

const text = (value: string): ArticleNode => ({ type: "text", text: value });
const paragraph = (value: string): ArticleNode => ({
  type: "paragraph",
  content: [text(value)],
});
const heading = (value: string, level: 2 | 3 = 2): ArticleNode => ({
  type: "heading",
  attrs: { level },
  content: [text(value)],
});
const bulletList = (items: string[]): ArticleNode => ({
  type: "bulletList",
  content: items.map((item) => ({
    type: "listItem",
    content: [paragraph(item)],
  })),
});

